export function getGradientFromSeed (seed: string | number) : Array<string> {
  const str = String(seed);
  let hash = 0;
  
  // A simple bitwise hash to turn the string into a unique number
  for (let i = 0; i < str.length; i++) {
    hash = str.charCodeAt(i) + ((hash << 5) - hash);
  }

  // Ensure positive number and map to array length
  const index = Math.abs(hash) % gradients.length;
  
  return gradients[index];
};